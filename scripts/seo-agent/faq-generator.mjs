// ─── Main ─────────────────────────────────────────────────────────────────────

/**
 * Run the FAQ generator.
 *
 * 1. Counts projects and micro-markets in Supabase
 * 2. Writes src/data/seo/project-faqs.ts
 * 3. Writes src/data/seo/micromarket-faqs.ts
 *
 * @returns {{ projectFaqFileWritten: boolean, microMarketFaqFileWritten: boolean, projectCount: number, microMarketCount: number }}
 */
export async function runFaqGenerator() {
  const result = {
    projectFaqFileWritten: false,
    microMarketFaqFileWritten: false,
    projectCount: 0,
    microMarketCount: 0,
  };

  // ── 1. Count records ──────────────────────────────────────────────────────

  let supabase;
  try {
    supabase = getSupabaseClient();
  } catch (err) {
    console.error("[faq-generator] Failed to initialise Supabase client:", err.message);
    // Still write the files even if DB is unavailable
  }

  if (supabase) {
    try {
      const { count: projectCount, error: projectErr } = await supabase
        .from("listing_project_detail_enriched_mv")
        .select("*", { count: "exact", head: true });

      if (projectErr) {
        console.error("[faq-generator] Error counting projects:", projectErr.message);
      } else {
        result.projectCount = projectCount ?? 0;
        console.error("[faq-generator] Projects in DB:", result.projectCount);
      }
    } catch (err) {
      console.error("[faq-generator] Unexpected error counting projects:", err.message);
    }

    try {
      const { count: mmCount, error: mmErr } = await supabase
        .from("micro_markets")
        .select("*", { count: "exact", head: true });

      if (mmErr) {
        console.error("[faq-generator] Error counting micro-markets:", mmErr.message);
      } else {
        result.microMarketCount = mmCount ?? 0;
        console.error("[faq-generator] Micro-markets in DB:", result.microMarketCount);
      }
    } catch (err) {
      console.error("[faq-generator] Unexpected error counting micro-markets:", err.message);
    }
  }

  // ── 2. Ensure output directory exists ────────────────────────────────────

  // Resolve relative to repo root (two levels up from scripts/seo-agent/)
  const repoRoot = path.resolve(
    path.dirname(new URL(import.meta.url).pathname),
    "..",
    ".."
  );
  const outputDir = path.join(repoRoot, "src", "data", "seo");

  try {
    fs.mkdirSync(outputDir, { recursive: true });
    console.error("[faq-generator] Output directory ready:", outputDir);
  } catch (err) {
    console.error("[faq-generator] Failed to create output directory:", err.message);
    return result;
  }

  // ── 3. Write project-faqs.ts ──────────────────────────────────────────────

  const projectFaqPath = path.join(outputDir, "project-faqs.ts");
  try {
    fs.writeFileSync(projectFaqPath, buildProjectFaqsTs(), "utf8");
    result.projectFaqFileWritten = true;
    console.error("[faq-generator] Wrote", projectFaqPath);
  } catch (err) {
    console.error("[faq-generator] Failed to write project-faqs.ts:", err.message);
  }

  // ── 4. Write micromarket-faqs.ts ─────────────────────────────────────────

  const mmFaqPath = path.join(outputDir, "micromarket-faqs.ts");
  try {
    fs.writeFileSync(mmFaqPath, buildMicroMarketFaqsTs(), "utf8");
    result.microMarketFaqFileWritten = true;
    console.error("[faq-generator] Wrote", mmFaqPath);
  } catch (err) {
    console.error("[faq-generator] Failed to write micromarket-faqs.ts:", err.message);
  }

  console.error(
    "[faq-generator] Done. projects=" + result.projectCount +
    ", micro-markets=" + result.microMarketCount +
    ", projectFaqFile=" + result.projectFaqFileWritten +
    ", microMarketFaqFile=" + result.microMarketFaqFileWritten
  );

  return result;
}
